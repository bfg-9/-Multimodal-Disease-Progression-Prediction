# Multimodal Disease Progression Prediction
# Combines EHR, imaging and genomics data to predict disease progression

import pandas as pd
import numpy as np
import torch
from torch import nn
from sklearn.model_selection import train_test_split
from sklearn.metrics import accuracy_score
import torchvision.models as models # type: ignore
from transformers import BertTokenizer, BertModel

# Simulated Data Loaders
def load_ehr_data():
    return pd.DataFrame(np.random.rand(100, 10)), np.random.randint(0, 2, 100)

def load_image_data():
    return torch.rand(100, 3, 224, 224)  # Simulated image data

def load_genomic_data():
    return pd.DataFrame(np.random.rand(100, 500))

# Define Model
class MultimodalModel(nn.Module):
    def __init__(self):
        super(MultimodalModel, self).__init__()
        self.ehr_fc = nn.Sequential(nn.Linear(10, 32), nn.ReLU())
        self.img_model = models.resnet18(pretrained=False)
        self.img_model.fc = nn.Linear(512, 32)
        self.genomic_fc = nn.Sequential(nn.Linear(500, 32), nn.ReLU())
        self.classifier = nn.Sequential(nn.Linear(96, 32), nn.ReLU(), nn.Linear(32, 2))

    def forward(self, ehr, img, genomic):
        ehr_out = self.ehr_fc(ehr)
        img_out = self.img_model(img)
        genomic_out = self.genomic_fc(genomic)
        combined = torch.cat((ehr_out, img_out, genomic_out), dim=1)
        return self.classifier(combined)

# Prepare Data
ehr_data, labels = load_ehr_data()
image_data = load_image_data()
genomic_data = load_genomic_data()

ehr_tensor = torch.tensor(ehr_data.values, dtype=torch.float32)
image_tensor = image_data
genomic_tensor = torch.tensor(genomic_data.values, dtype=torch.float32)
labels_tensor = torch.tensor(labels, dtype=torch.long)

# Model Training
model = MultimodalModel()
criterion = nn.CrossEntropyLoss()
optimizer = torch.optim.Adam(model.parameters(), lr=0.001)

for epoch in range(5):
    optimizer.zero_grad()
    outputs = model(ehr_tensor, image_tensor, genomic_tensor)
    loss = criterion(outputs, labels_tensor)
    loss.backward()
    optimizer.step()
    print(f"Epoch {epoch+1}, Loss: {loss.item():.4f}")

# Inference
with torch.no_grad():
    preds = model(ehr_tensor, image_tensor, genomic_tensor)
    pred_labels = torch.argmax(preds, dim=1)
    acc = accuracy_score(labels, pred_labels.numpy())
    print(f"Accuracy: {acc:.2f}")